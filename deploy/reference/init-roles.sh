#!/usr/bin/env bash
set -euo pipefail
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" \
    -v migrator="$MIGRATOR_PASSWORD" -v runtime="$RUNTIME_PASSWORD" -v tenant="$TENANT_PASSWORD" <<'SQL'
CREATE ROLE sb_migrator LOGIN NOSUPERUSER NOCREATEROLE NOCREATEDB NOBYPASSRLS PASSWORD :'migrator';
CREATE ROLE sb_runtime LOGIN NOSUPERUSER NOCREATEROLE NOCREATEDB NOBYPASSRLS PASSWORD :'runtime';
CREATE ROLE sb_tenant LOGIN NOSUPERUSER NOCREATEROLE NOCREATEDB NOBYPASSRLS PASSWORD :'tenant';
REVOKE ALL ON DATABASE superbackend FROM PUBLIC;
ALTER DATABASE superbackend OWNER TO sb_migrator;
GRANT CONNECT ON DATABASE superbackend TO sb_runtime, sb_tenant;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
SQL
